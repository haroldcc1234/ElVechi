export async function seedDatabase(force = false): Promise<void> {
  const current = await db.settings.get('seedVersion');
  if (!force && current?.value === SEED_VERSION) return;

  await db.transaction(
    'rw',
    [
      db.profiles,
      db.providers,
      db.endorsements,
      db.listings,
      db.requests,
      db.alerts,
      db.brigadeProfiles,
      db.notifications,
      db.reputationEvents,
      db.reports,
      db.syncQueue,
      db.settings,
    ],
    async () => {
      await Promise.all([
        db.profiles.clear(),
        db.providers.clear(),
        db.endorsements.clear(),
        db.listings.clear(),
        db.requests.clear(),
        db.alerts.clear(),
        db.brigadeProfiles.clear(),
        db.notifications.clear(),
        db.reputationEvents.clear(),
        db.reports.clear(),
        db.syncQueue.clear(),
        db.settings.clear(),
      ]);

      await db.profiles.bulkAdd(profiles);
      await db.providers.bulkAdd(providers);
      await db.endorsements.bulkAdd(endorsements);
      await db.listings.bulkAdd(listings);
      await db.requests.bulkAdd(requests);
      await db.alerts.bulkAdd(alerts);
      await db.brigadeProfiles.bulkAdd(brigadeProfiles);
      await db.notifications.bulkAdd(notifications);
      await db.reputationEvents.bulkAdd(reputationEvents);
      await db.reports.bulkAdd(reports);
      await db.settings.bulkAdd(settings);
    },
  );

  await serverDb.transaction(
    'rw',
    serverDb.records,
    serverDb.processedOps,
    async () => {
      await serverDb.records.clear();
      await serverDb.processedOps.clear();
    },
  );
}
